-- wishlists repository
CREATE TABLE lists (
	id bigint UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY COMMENT 'Autogenerated list identity',
	title text NOT NULL COMMENT 'Heading of the Wishlist',
	color varchar(32) NOT NULL DEFAULT '#0ea5e9' COMMENT 'Color to personalize the Wishlist',
	description text COMMENT 'Longer description of the Wishlist',
	slug_public varchar(64) NOT NULL COMMENT 'URL Segment to build public link',
	slug_private varchar(64) NOT NULL COMMENT 'URL Segment to build private link',
	spoiler bool NOT NULL DEFAULT false COMMENT 'Show reservations and purchases on private view',
	created datetime NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT 'Timestamp of list creation',
	modified datetime(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6) COMMENT 'Timestamp of last change to list or its items, used for syncing',
	UNIQUE KEY slug_public (slug_public)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='Wishlists';

-- wishlist items repository
CREATE TABLE items (
	id bigint UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY COMMENT 'Autogenerated item identity',
	list bigint UNSIGNED NOT NULL COMMENT 'Reference to wishlist item belongs to',
	title text NOT NULL COMMENT 'Heading of list item',
	price text COMMENT 'Estimated price of list item',
	description text COMMENT 'Longer description of list item',
	links json COMMENT 'At least one link to a shop, where item can be bought',
	state enum('open', 'reserved', 'purchased') NOT NULL DEFAULT 'open' COMMENT 'Item status, can be open, reserved or purchased',
	weight bigint NOT NULL DEFAULT 0 COMMENT 'Position of item in list',
	created datetime NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT 'Timestamp of list item creation',
	modified datetime(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6) COMMENT 'Timestamp of list item modification',
	FOREIGN KEY (list) REFERENCES lists (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='Wishlist items';
